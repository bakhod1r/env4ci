// initPlan is everything "env4ci init" writes into env4ci.yaml.
type initPlan struct {
	Dir          string            // folder for generated files (see secretsDirFor); "" = root
	remote       string            // git remote provider, decides Dir
	Targets      []string          // github, gitlab, vault, jenkins
	Environments []string          // one or many
	branchOf     map[string]string // environment -> real branch it was derived from
	Repo         string            // owner/name or group/project
	VaultAddr    string
	VaultMount   string
	VaultPath    string
	JenkinsURL   string
}

// branchFor guesses the branch that deploys to env.
func branchFor(env string) string {
	switch env {
	case "production", "prod":
		return "main"
	case "staging", "stage":
		return "develop"
	}
	return env
}

// envForBranch names the environment a branch deploys to: the inverse of
// branchFor, else the branch's own name (see branchSlug).
func envForBranch(branch string) string {
	switch branch {
	case "main", "master":
		return "production"
	case "develop", "dev":
		return "staging"
	}
	return first(branchSlug(branch), "production")
}

// branchSlug is a branch name usable as an environment name: lower case,
// anything but letters, digits, - and _ turned into "-".
func branchSlug(branch string) string {
	return strings.Trim(strings.Map(func(r rune) rune {
		if keyLike(string(r)) {
			return r
		}
		return '-'
	}, strings.ToLower(branch)), "-")
}

// BranchOf is the branch that deploys to env: the checked-out branch the
// environment came from, else a guess.
func (p initPlan) BranchOf(env string) string {
	if b, ok := p.branchOf[env]; ok {
		return b
	}
	return branchFor(env)
}

// secretsDirFor puts generated files in the CI folder itself: .github for
// GitHub, .gitlab for GitLab (the git remote decides when both are
// targets), or the project root for Vault-only. Each file is gitignored.
func secretsDirFor(targets []string, remoteProvider string) string {
	has := func(t string) bool { return contains(targets, t) }
	switch {
	case has(remoteProvider) && remoteProvider == "gitlab":
		return ".gitlab"
	case has("github"):
		return ".github"
	case has("gitlab"):
		return ".gitlab"
	}
	return ""
}

// envFileFor: <dir>/<env>.env, or .env.<env> at the project root.
func envFileFor(dir, env string) string {
	if dir == "" {
		return ".env." + env
	}
	return dir + "/" + env + ".env"
}

// authFileFor: <dir>/env4ci.env, or .env.env4ci at the project root.
func authFileFor(dir string) string {
	if dir == "" {
		return config.DefaultAuthFile
	}
	return dir + "/env4ci.env"
}

var initTmpl = template.Must(template.New("init").Funcs(template.FuncMap{
	"file": envFileFor, "auth": authFileFor, "q": func(s string) string { return fmt.Sprintf("%q", s) },
	"has": func(xs []string, x string) bool {
		for _, v := range xs {
			if v == x {
				return true
			}
		}
		return false
	},
}).Parse(`# env4ci configuration (generated by "env4ci init").
# Tokens come from GITHUB_TOKEN / GITLAB_TOKEN / VAULT_TOKEN, never this file.

# Unmatched keys default to secret (safe). First matching rule wins.
default: secret
rules:
  - { pattern: "*SECRET*",   type: secret }
  - { pattern: "*PASSWORD*", type: secret }
  - { pattern: "*TOKEN*",    type: secret }
  - { pattern: "*KEY*",      type: secret }
  - { pattern: "APP_*",      type: variable }
  - { pattern: "LOG_*",      type: variable }
  - { pattern: "ENVIRONMENT", type: variable }

# Branch -> environment. "env4ci push" on a branch writes to its environment.
branches:
{{- range .Environments}}
  {{$.BranchOf . | q}}: {{.}}
{{- end}}

# env4ci's own tokens/addresses (generated, gitignored).
auth_file: {{auth .Dir}}

# One JSON line per push: who, when, where, which keys (never values). Commit it.
audit_log: env4ci-audit.jsonl

# Environment -> local file. Each file is gitignored; the folder stays tracked.
environments:
{{- range .Environments}}
  {{.}}: {{file $.Dir .}}
{{- end}}

targets:
{{- if has .Targets "github"}}
  github:
    repo: {{if .Repo}}{{.Repo}}{{else}}owner/name{{end}}
{{- end}}
{{- if has .Targets "gitlab"}}
  gitlab:
    project: {{if .Repo}}{{.Repo}}{{else}}group/project{{end}}
    protected: true
{{- end}}
{{- if has .Targets "vault"}}
  vault:
    address: {{if .VaultAddr}}{{.VaultAddr}}{{else}}https://vault.example.com:8200{{end}}
    mount: {{.VaultMount}}
    path: {{.VaultPath}}   # {env} = environment name
{{- end}}
{{- if has .Targets "jenkins"}}
  jenkins:
    url: {{if .JenkinsURL}}{{.JenkinsURL}}{{else}}https://jenkins.example.com{{end}}
    # folder: myapp/{env}   # omit for the system credentials store
{{- end}}
`))

// config is the Config renderInit's YAML describes (tests assert they match).
func (p initPlan) config() config.Config {
	p.Dir = secretsDirFor(p.Targets, p.remote)
	c := config.Config{
		Default: "secret",
		Rules: []config.Rule{
			{Pattern: "*SECRET*", Type: "secret"}, {Pattern: "*PASSWORD*", Type: "secret"},
			{Pattern: "*TOKEN*", Type: "secret"}, {Pattern: "*KEY*", Type: "secret"},
			{Pattern: "APP_*", Type: "variable"}, {Pattern: "LOG_*", Type: "variable"},
			{Pattern: environmentKey, Type: "variable"},
		},
		AuthFile:     authFileFor(p.Dir),
		AuditLog:     "env4ci-audit.jsonl",
		Branches:     map[string]string{},
		Environments: map[string]string{},
	}
	for _, e := range p.Environments {
		c.Branches[p.BranchOf(e)] = e
		c.Environments[e] = envFileFor(p.Dir, e)
	}
	for _, t := range p.Targets {
		switch t {
		case "github":
			c.Targets.GitHub = &config.GitHub{Repo: first(p.Repo, "owner/name")}
		case "gitlab":
			c.Targets.GitLab = &config.GitLab{Project: first(p.Repo, "group/project"), Protected: true}
		case "vault":
			c.Targets.Vault = &config.Vault{Address: first(p.VaultAddr, "https://vault.example.com:8200"), Mount: p.VaultMount, Path: p.VaultPath}
		case "jenkins":
			c.Targets.Jenkins = &config.Jenkins{URL: first(p.JenkinsURL, "https://jenkins.example.com")}
		}
	}
	return c
}

func renderInit(p initPlan) ([]byte, error) {
	p.Dir = secretsDirFor(p.Targets, p.remote)
	if len(p.Targets) == 0 {
		return nil, errors.New("init: at least one target (github, gitlab, vault, jenkins)")
	}
	if len(p.Environments) == 0 {
		return nil, errors.New("init: at least one environment")
	}
	for _, t := range p.Targets {
		if t != "github" && t != "gitlab" && t != "vault" && t != "jenkins" {
			return nil, fmt.Errorf("init: unknown target %q (want github, gitlab, vault, jenkins)", t)
		}
	}
	for _, e := range p.Environments {
		if !keyLike(e) {
			return nil, fmt.Errorf("init: environment %q: use letters, digits, - or _", e)
		}
	}
	seen := map[string]string{}
	for _, e := range p.Environments {
		b := p.BranchOf(e)
		if prev, dup := seen[b]; dup {
			return nil, fmt.Errorf("init: environments %q and %q both map to branch %q; edit branches: after init", prev, e, b)
		}
		seen[b] = e
	}
	// Inputs are validated above; the template only formats strings into a
	// buffer, so Execute cannot fail. Tests load every output with config.Load.
	var buf bytes.Buffer
	_ = initTmpl.Execute(&buf, p)
	return buf.Bytes(), nil
}

func keyLike(s string) bool {
	if s == "" {
		return false
	}
	for _, r := range s {
		ok := r == '-' || r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9'
		if !ok {
			return false
		}
	}
	return true
}

func splitList(s string) []string {
	var out []string
	for _, p := range strings.FieldsFunc(s, func(r rune) bool { return r == ',' || r == ' ' }) {
		out = append(out, strings.ToLower(strings.TrimSpace(p)))
	}
	return out
}

// defaultsFromGit pre-fills targets and repo from the remote, and the
// environment from the checked-out branch (production when it is unknown).
func defaultsFromGit(git gitReader) initPlan {
	p := initPlan{Targets: []string{"github"}, Environments: []string{"production"}, VaultMount: "secret"}
	if r, err := git.Remote(); err == nil {
		p.Repo = r.Path
		p.remote = r.Provider
		if r.Provider != "" {
			p.Targets = []string{r.Provider}
		}
	}
	if b, err := git.Branch(); err == nil && b != "" {
		env := envForBranch(b)
		p.Environments = []string{env}
		p.branchOf = map[string]string{env: b}
	}
	p.VaultAddr = os.Getenv("VAULT_ADDR")
	name := "app"
	if p.Repo != "" {
		name = path.Base(p.Repo)
	}
	p.VaultPath = name + "/{env}"
	return p
}

// ciEnvironment is an environment the CI files deploy to. Branch is the
// single branch its jobs run on, "" when they run on several or on all.
// FromBranch marks one CI does not name: it was derived from Branch.
type ciEnvironment struct {
	Name, Branch string
	FromBranch   bool
}

// ciEnvironments lists the environments refs name, sorted. Shared scope and
// names env4ci cannot use (an expression like ${{ inputs.target }}) are left
// out. When CI names none, the branches its jobs run on decide (see
// environmentsFromBranches).
func ciEnvironments(refs []domain.Reference) []ciEnvironment {
	var envs []ciEnvironment
	for _, g := range domain.GroupByEnvironment(refs) {
		if !keyLike(g.Environment) {
			continue
		}
		e := ciEnvironment{Name: g.Environment}
		if branches := plainBranches(g.Refs); len(branches) == 1 {
			e.Branch = branches[0]
		}
		envs = append(envs, e)
	}
	if len(envs) == 0 {
		envs = environmentsFromBranches(refs)
	}
	sort.Slice(envs, func(i, j int) bool { return envs[i].Name < envs[j].Name })
	return envs
}

// plainBranches lists the exact branch names refs run on, in first-seen
// order: no "every branch", tags, globs or regular expressions.
func plainBranches(refs []domain.Reference) []string {
	var out []string
	for _, r := range refs {
		for _, b := range r.Branches {
			if b != domain.BranchAll && !strings.ContainsAny(b, `*?[]()^$\`) && !contains(out, b) {
				out = append(out, b)
			}
		}
	}
	return out
}

// environmentsFromBranches makes one environment per branch the CI jobs run
// on ("on: push: branches: [dev, main]"), for CI files that name no
// environment. A job deploying to ${{ github.ref_name }} means the
// environment is the branch's own name; otherwise envForBranch decides
// (main -> production, dev -> staging).
func environmentsFromBranches(refs []domain.Reference) []ciEnvironment {
	name := envForBranch
	for _, r := range refs {
		if strings.Contains(r.Environment, "github.ref_name") {
			name = branchSlug
		}
	}
	var envs []ciEnvironment
	seen := map[string]bool{}
	for _, b := range plainBranches(refs) {
		if n := name(b); n != "" && !seen[n] {
			seen[n] = true
			envs = append(envs, ciEnvironment{Name: n, Branch: b, FromBranch: true})
		}
	}
	return envs
}

// environmentsFromCI replaces the branch-derived environment with the ones
// the CI files under root deploy to; p is returned unchanged when they name
// none. An environment's branch is the single branch its CI jobs run on,
// else the checked-out branch it was derived from, else a guess.
func environmentsFromCI(p initPlan, root string) (initPlan, error) {
	cl, _ := p.config().Classifier() // init's own rules: always valid
	refs, err := ciscan.Scan(root, cl)
	if err != nil {
		return p, err
	}
	var envs []string
	branchOf := map[string]string{}
	used := map[string]bool{}
	for _, e := range ciEnvironments(refs) {
		branch := first(e.Branch, p.BranchOf(e.Name))
		if used[branch] {
			branch = e.Name
		}
		used[branch] = true
		branchOf[e.Name] = branch
		envs = append(envs, e.Name)
	}
	if len(envs) == 0 {
		return p, nil
	}
	p.Environments, p.branchOf = envs, branchOf
	return p, nil
}

// askInit prompts on in/out; empty answers keep defaults. Environments are
// never asked: they come from the CI files, else the branch (or --envs).
func askInit(in io.Reader, out io.Writer, d initPlan) initPlan {
	r := bufio.NewReader(in)
	ask := func(q, def string) string {
		fmt.Fprintf(out, "%s [%s]: ", q, def)
		line, _ := r.ReadString('\n')
		if line = strings.TrimSpace(line); line != "" {
			return line
		}
		return def
	}
	d.Targets = splitList(ask("Targets (github, gitlab, vault, jenkins; comma-separated)", strings.Join(d.Targets, ",")))
	if contains(d.Targets, "github") || contains(d.Targets, "gitlab") {
		d.Repo = ask("Repository (owner/name or group/project)", first(d.Repo, "owner/name"))
	}
	if contains(d.Targets, "vault") {
		d.VaultAddr = ask("Vault address", first(d.VaultAddr, "https://vault.example.com:8200"))
		d.VaultMount = ask("Vault KV v2 mount", d.VaultMount)
		d.VaultPath = ask("Vault path ({env} = environment)", d.VaultPath)
	}
	if contains(d.Targets, "jenkins") {
		d.JenkinsURL = ask("Jenkins URL", first(d.JenkinsURL, os.Getenv("JENKINS_URL"), "https://jenkins.example.com"))
	}
	return d
}

func contains(xs []string, x string) bool {
	for _, v := range xs {
		if v == x {
			return true
		}
	}
	return false
}

func isTerminal(r io.Reader) bool {
	f, ok := r.(*os.File)
	if !ok {
		return false
	}
	st, err := f.Stat()
	return err == nil && st.Mode()&os.ModeCharDevice != 0
}

// cmdInitWizard writes env4ci.yaml (refuses to overwrite), creates an empty
// .env file per environment if missing, and gitignores them.
func cmdInitWizard(o opts, in io.Reader, out io.Writer, git gitReader, interactive bool) error {
	p := defaultsFromGit(git)
	switch {
	case o.targets != "" || o.envs != "":
		if o.targets != "" {
			p.Targets = splitList(o.targets)
		}
		if o.envs != "" {
			p.Environments = splitList(o.envs)
		}
		if o.repo != "" {
			p.Repo = o.repo
		}
	case interactive:
		p = askInit(in, out, p)
	}
	if o.envs == "" {
		var err error
		if p, err = environmentsFromCI(p, first(o.dir, filepath.Dir(o.config))); err != nil {
			return err
		}
	}
	b, err := renderInit(p)
	if err != nil {
		return err
	}
	if err := writeNew(o.config, b, 0o644); err != nil {
		return err
	}
	ui := newPalette(out)
	fmt.Fprintf(out, "%s wrote %s (targets: %s; environments: %s)\n", ui.Green("✓"), o.config, strings.Join(p.Targets, ", "), strings.Join(p.Environments, ", "))
	for _, e := range p.Environments {
		fmt.Fprintf(out, "  branch %s -> environment %s\n", p.BranchOf(e), e)
	}

	o.fixedEnvs = true
	if err := cmdGen(p.config(), o, nil, out); err != nil {
		return err
	}
	if err := writeMakefile(filepath.Join(filepath.Dir(o.config), "Makefile"), out); err != nil {
		return err
	}
	fmt.Fprintln(out, ui.Dim("next: put tokens in "+p.config().AuthPath()+", fill the environment files, then run \"env4ci diff\""))
	return nil
}
